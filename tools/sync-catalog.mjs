import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { builtins } from '../characters/builtins.js';
import { buildCatalog } from '../characters/metadata.js';
export const ROOT = fileURLToPath(new URL('../', import.meta.url));

export async function discoverCharacters(root = ROOT) {
  const directory = path.join(root, 'characters'), entries = [];
  for (const folder of (await readdir(directory, { withFileTypes: true })).sort((a,b)=>a.name.localeCompare(b.name))) {
    if (!folder.isDirectory()) continue;
    const source = `characters/${folder.name}/character.js`, file = path.join(root, source);
    try { await readFile(file); } catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    try {
      const { character, studio } = await import(pathToFileURL(file).href);
      entries.push({ definition: character, studio, source, exportName: 'character', builtin: false });
    } catch (error) { throw new Error(`${source}: 読み込みに失敗しました — ${error.message}`); }
  }
  return buildCatalog([...builtins, ...entries]);
}

export async function syncCatalog({ root = ROOT, check = false } = {}) {
  const catalog = await discoverCharacters(root), additions = catalog.filter(c => !c.builtin);
  const imports = additions.map((c,i)=>`import { character as c${i}, studio as m${i} } from ${JSON.stringify('./'+c.source.slice('characters/'.length))};`);
  const lines = additions.map((c,i)=>`  { definition: c${i}, studio: m${i}, source: ${JSON.stringify(c.source)}, exportName: 'character', builtin: false },`);
  const text = `// Generated by node tools/sync-catalog.mjs. Do not edit.\n${imports.join('\n')}\nexport const additions = [\n${lines.join('\n')}\n];\n`;
  const output = path.join(root, 'characters/catalog.generated.js');
  if (check) {
    if (await readFile(output, 'utf8').catch(()=>null) !== text) throw new Error('カタログが未更新です。node tools/sync-catalog.mjs を実行してください');
  } else await writeFile(output, text);
  return catalog;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.slice(2).some(a=>a!=='--check')) throw new Error('使い方: node tools/sync-catalog.mjs [--check]');
    const catalog = await syncCatalog({ check: process.argv.includes('--check') });
    console.log(`カタログ確認完了: ${catalog.length}体 (${catalog.map(c=>c.id).join(', ')})`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
